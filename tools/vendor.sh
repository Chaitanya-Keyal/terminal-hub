#!/usr/bin/env bash
# Refresh the third-party files in web/vendor (xterm.js, its addons and their type definitions)
# and web/icons.js (Lucide icons), at the versions pinned below. Run it from anywhere; it needs
# curl, openssl and python3.
#   tools/vendor.sh
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")/.."

XTERM=(@xterm/xterm@6.0.0 @xterm/addon-fit@0.11.0 @xterm/addon-webgl@0.19.0
  @xterm/addon-unicode11@0.9.0 @xterm/addon-web-links@0.12.0)
LUCIDE=1.65.0
# Icons the page uses, then the ones for places and categories (config: icon, category; the
# page's icon picker; docs/config.md lists them). Any other name shows as text, so an emoji works.
UI_ICONS=(a-arrow-down a-arrow-up arrow-down arrow-left arrow-left-right arrow-right arrow-up
  bell bell-off check chevron-left chevron-right clipboard-paste columns-2 ellipsis history
  keyboard loader-circle lock panel-left paperclip pencil plus rotate-cw search settings
  square-terminal tag trash-2 wifi-off x)
PLACE_ICONS=(bitcoin book-open bot brain briefcase bug building-2 box chart-line cloud code
  coffee container cpu database flame flask-conical folder folder-git-2 gamepad-2 gem git-branch
  globe graduation-cap hammer hard-drive heart house key-round laptop layers leaf mail monitor
  moon mountain music package palette puzzle rocket router server shield smartphone sparkles star
  sun target terminal user users wallet wrench zap)
ICONS=("${UI_ICONS[@]}" "${PLACE_ICONS[@]}")

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p web/vendor/types

for spec in "${XTERM[@]}"; do
  pkg=${spec%@*} ver=${spec##*@} name=${pkg#*/}
  meta=$(curl -fsS --retry 3 "https://registry.npmjs.org/${pkg/\//%2f}/$ver")
  url=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["dist"]["tarball"])' <<<"$meta")
  want=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["dist"]["integrity"])' <<<"$meta")
  curl -fsS --retry 3 -o "$tmp/$name.tgz" "$url"
  got="sha512-$(openssl dgst -sha512 -binary "$tmp/$name.tgz" | base64 -w0)"
  [[ $got == "$want" ]] || { echo "$spec: checksum mismatch" >&2; exit 1; }
  mkdir -p "$tmp/$name" && tar -xzf "$tmp/$name.tgz" -C "$tmp/$name"
  cp "$tmp/$name/package/lib/$name.mjs" web/vendor/
  cp "$tmp/$name/package/typings/$name.d.ts" web/vendor/types/  # for `tsc` (see tsconfig.json)
  echo "$spec"
done
cp "$tmp/xterm/package/css/xterm.css" web/vendor/
cp "$tmp/xterm/package/LICENSE" web/vendor/xterm-LICENSE

mkdir -p "$tmp/lucide"
for i in "${ICONS[@]}"; do
  curl -fsS --retry 3 -o "$tmp/lucide/$i.svg" "https://cdn.jsdelivr.net/npm/lucide-static@$LUCIDE/icons/$i.svg"
done
curl -fsS --retry 3 -o web/vendor/lucide-LICENSE "https://cdn.jsdelivr.net/npm/lucide-static@$LUCIDE/LICENSE"
python3 -I - "$tmp/lucide" "$LUCIDE" "${PLACE_ICONS[*]}" >web/icons.js <<'PY'
import json, pathlib, re, sys
src, version, pickable = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3].split()
print(f"// Lucide icons {version} (https://lucide.dev, ISC licence: vendor/lucide-LICENSE).")
print("// Generated by tools/vendor.sh: edit the list there, not this file.")
print("const PATHS = {")
for f in sorted(src.glob("*.svg")):
    body = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(), re.S).group(1)
    body = re.sub(r"\s*\n\s*", "", body).replace(" />", "/>")
    print(f"  '{f.stem}': '{body}',")
print("};")
print("""
// icon('plus') → an <svg class="icon"> drawn with currentColor; size comes from CSS.
export function icon(name, label) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', 'icon');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  if (label) svg.setAttribute('aria-label', label); else svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = PATHS[name] ?? '';
  return svg;
}

export const hasIcon = name => Object.hasOwn(PATHS, name);""")
print("// The icons for places and categories, for the page's icon picker.")
print(f"export const PLACE_ICONS = {json.dumps(pickable)};")
PY
echo "lucide-static@$LUCIDE (${#ICONS[@]} icons)"
